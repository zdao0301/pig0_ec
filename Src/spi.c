void COMPO_SPI_receive(void)
{
	/* 与 C6T6 主机完全一致的 CS 时序：NSS 低电平仅覆盖帧长（~50µs），
	   帧结束立即释放 NSS，其余时间保持高电平——避免从机长时间处于
	   "被选通但无时钟"状态（F1 从机 TX 状态机在该状态下会错乱） */
	if(hspi2.State == HAL_SPI_STATE_READY)
	{
		HAL_GPIO_WritePin(SPI2_CS_GPIO_Port, SPI2_CS_Pin, GPIO_PIN_RESET);//software cs
		HAL_SPI_TransmitReceive_IT(&hspi2, compo_t, compo_r, 4);
	}
	else
	{
		/* 传输未就绪/异常：保持 NSS 高电平 */
		HAL_GPIO_WritePin(SPI2_CS_GPIO_Port, SPI2_CS_Pin, GPIO_PIN_SET);
	}

	//handmade data analyzer
//	an1=HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_12);
//	an2=HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_13);
//	an3=HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_14);
//	an4=HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_15);
}

void HAL_SPI_TxRxCpltCallback(SPI_HandleTypeDef *hspi)
{
    if (hspi->Instance == SPI2)
		{
			HAL_GPIO_WritePin(SPI2_CS_GPIO_Port, SPI2_CS_Pin, GPIO_PIN_SET); /* 帧结束立即释放 NSS */

    compo_r_hist[compo_r_frame_cnt % 16][0] = compo_r[0];
    compo_r_hist[compo_r_frame_cnt % 16][1] = compo_r[1];
    compo_r_hist[compo_r_frame_cnt % 16][2] = compo_r[2];
    compo_r_hist[compo_r_frame_cnt % 16][3] = compo_r[3];
    compo_r_hist_tick[compo_r_frame_cnt % 16] = HAL_GetTick();
    compo_r_frame_cnt++;
    }
}
